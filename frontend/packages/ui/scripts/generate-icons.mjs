// Generates a React component for every SVG in src/icons/svg into src/icons/react, plus the
// barrel src/icons/index.ts. Run it (`npm run icons -w @crm/ui`) after adding or removing icons.
// Icons use currentColor unless a `color` prop is passed.
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from '@svgr/core';
import jsx from '@svgr/plugin-jsx';

const here = path.dirname(fileURLToPath(import.meta.url));
const icons = path.join(here, '..', 'src', 'icons');
const out = path.join(icons, 'react');

const pascal = (base) =>
  base
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('');

const svgrConfig = {
  plugins: [jsx],
  svgo: false,
  jsxRuntime: 'automatic',
  replaceAttrValues: { currentColor: '{props.color || "currentColor"}' },
  svgProps: {
    'data-animate': '{props.isAnimate || false}',
    'data-interactive': '{props.animateOnInteraction || false}',
  },
};

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

const names = [];
for (const file of (await readdir(path.join(icons, 'svg')))
  .filter((f) => f.endsWith('.svg'))
  .sort()) {
  const name = pascal(file.slice(0, -4));
  const svg = await readFile(path.join(icons, 'svg', file), 'utf8');
  const code = await transform(svg, svgrConfig, { componentName: name });
  await writeFile(
    path.join(out, `${name}.jsx`),
    `// GENERATED from ../svg/${file} by scripts/generate-icons.mjs\n${code}\n`,
  );
  names.push(name);
}

await writeFile(
  path.join(icons, 'index.ts'),
  `// GENERATED by scripts/generate-icons.mjs: one export per icon.\n` +
    names.map((n) => `export { default as ${n} } from './react/${n}'`).join('\n') +
    '\n',
);
console.log(`${names.length} icons generated`);
